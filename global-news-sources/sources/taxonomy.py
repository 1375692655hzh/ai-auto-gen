def norm_sector(path: str) -> str:
    """存量赛道路径归一化: "L1>L2[>L3]" → 正典 "L1>L2"(保L3)。

    规则: L1 不在枚举→返回""(整条丢弃); L2 在枚举→保留; 别名命中→改正;
    未命中→L2降级为"其他"。L3 原样保留(开放层)。
    """
    parts = [p.strip() for p in str(path).split(">") if p.strip()]
    if not parts or parts[0] not in L1_L2:
        return ""
    l1 = parts[0]
    l3 = parts[2] if len(parts) >= 3 else ""
    if len(parts) == 1:
        return l1                                     # 裸 L1 合法(纯宏观叙事)
    l2 = parts[1]
    if l2 not in L1_L2[l1]:
        if (l1, l2) in _CROSS:
            l1, l2 = _CROSS[(l1, l2)]
        else:
            l2 = _SAME.get(l1, {}).get(l2, "其他")
    return f"{l1}>{l2}>{l3}" if l3 else f"{l1}>{l2}"


def check_sector(l1: str, l2: str = "", l3: str = "") -> bool:
    """LLM 精标写库前校验: L1∈枚举, L2∈该L1枚举(可空), L3≤12字(可空)。"""
    if l1 not in L1_L2:
        return False
    if l2 and l2 not in L1_L2[l1]:
        return False
    if l3 and (len(l3) > 12 or ">" in l3):
        return False
    return True


